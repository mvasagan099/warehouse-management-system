#!/usr/bin/env python3
"""Builds supabase/tests/database/rls_matrix.test.sql from scripts/rls/fixtures.sql, the probe harness and scripts/rls/expected.txt.

expected.txt: one line per public table:  <table> <rows> <read> <insert> <update> <delete>
Each of read/insert/update/delete is five characters, one per role in the order  A C M S X
(SUPER_ADMIN, CLIENT, WAREHOUSE_MANAGER, STAFF, ACCOUNTANT):
   a = sees / may change every fixture row       p = only some rows (their own warehouse or client)
   - = nothing                                    x = row security lets them, a foreign key or a trigger still blocks (delete)
   ? = no fixture row exists for this table, so this cell is not checked (the privilege checks still apply)
Edit expected.txt only after reviewing why a cell changed, then run:  python3 scripts/rls/build.py
"""
import pathlib, re
root = pathlib.Path(__file__).resolve().parents[2]
fixtures = (root / 'scripts/rls/fixtures.sql').read_text()
draft = (root / 'scripts/rls/draft.sql').read_text()
harness = draft[draft.index('create temp table probe'):draft.index('select tbl, max(total)')]
rows = [l.split() for l in (root / 'scripts/rls/expected.txt').read_text().splitlines() if l.strip()]
n_tables = len(rows)
values = ',\n  '.join("('%s', '%s', '%s', '%s', '%s')" % (r[0], r[2], r[3], r[4], r[5]) for r in rows)
out = f"""-- GENERATED by scripts/rls/build.py from scripts/rls/expected.txt - do not edit by hand.
-- RLS matrix: every table x every role x read, insert, update, delete, against fixture rows in two warehouses and for two clients.
begin;
create extension if not exists pgtap with schema extensions;
set search_path = public, extensions;
select plan({n_tables * 4 + 13});

{fixtures}

{harness}

create temp table expected (tbl text primary key, r text, i text, u text, d text);
insert into expected values
  {values};

-- schema level
select is((select count(*)::int from pg_class c join pg_namespace n on n.oid = c.relnamespace where n.nspname = 'public' and c.relkind in ('r','p') and not c.relispartition and not c.relrowsecurity), 0, 'every table has row level security enabled');
select is((select string_agg(c.relname, ',') from pg_class c join pg_namespace n on n.oid = c.relnamespace where n.nspname = 'public' and c.relkind in ('r','p') and not c.relispartition and c.relname not in (select tbl from expected)), null, 'every table is covered by the matrix (add new tables to scripts/rls/expected.txt after review)');
select is((select count(*)::int from pg_class c join pg_namespace n on n.oid = c.relnamespace where n.nspname = 'public' and c.relkind in ('r','p') and (has_table_privilege('anon', c.oid, 'select') or has_table_privilege('anon', c.oid, 'insert') or has_table_privilege('anon', c.oid, 'update') or has_table_privilege('anon', c.oid, 'delete'))), 0, 'the anonymous role has no privilege on any table');
select is((select count(*)::int from pg_class c join pg_namespace n on n.oid = c.relnamespace cross join (values ('insert','INSERT'),('update','UPDATE'),('delete','DELETE'),('select','SELECT')) ops(op, cmd)
   where n.nspname = 'public' and c.relkind in ('r','p') and not c.relispartition and has_table_privilege('authenticated', c.oid, ops.op)
     and not exists (select 1 from pg_policies p where p.schemaname = 'public' and p.tablename = c.relname and p.cmd in (ops.cmd, 'ALL'))), 0, 'no table privilege exists without a policy that can use it');
select is((select count(*)::int from information_schema.columns where table_schema = 'public' and column_name in ('bank_account_no', 'service_key', 'secret') and table_name not in ('employee_private')), 0, 'sensitive columns exist only where reviewed');

-- profile protection: a user cannot promote themselves
select set_config('request.jwt.claims', '{{"sub":"f5000000-0000-0000-0000-000000000004","role":"authenticated"}}', false);
set local role authenticated;
select throws_ok($$ update public.profiles set role = 'SUPER_ADMIN' where id = 'f5000000-0000-0000-0000-000000000004' $$, '42501', null, 'a client cannot make themselves an administrator');
select throws_ok($$ update public.profiles set client_id = 'f4000000-0000-0000-0000-000000000002' where id = 'f5000000-0000-0000-0000-000000000004' $$, '42501', null, 'a client cannot move themselves to another client');
select set_config('request.jwt.claims', '{{"sub":"f5000000-0000-0000-0000-000000000003","role":"authenticated"}}', false);
select throws_ok($$ update public.profiles set warehouse_id = 'f1000000-0000-0000-0000-000000000002' where id = 'f5000000-0000-0000-0000-000000000003' $$, '42501', null, 'staff cannot move themselves to another warehouse');
select throws_ok($$ update public.profiles set is_active = false where id = 'f5000000-0000-0000-0000-000000000003' $$, '42501', null, 'staff cannot change their own account status');
reset role;

-- two-factor rule for the administrator
select is(public.mfa_required(), false, 'two-factor is off by default');
update public.app_settings set value = '{{"require_admin_mfa": true}}' where key = 'security';
select set_config('request.jwt.claims', '{{"sub":"f5000000-0000-0000-0000-000000000001","role":"authenticated","aal":"aal1"}}', false);
select is(public.is_admin(), false, 'with two-factor required, an administrator session without it is not an administrator');
select set_config('request.jwt.claims', '{{"sub":"f5000000-0000-0000-0000-000000000001","role":"authenticated","aal":"aal2"}}', false);
select is(public.is_admin(), true, 'and with it, they are');
update public.app_settings set value = '{{"require_admin_mfa": false}}' where key = 'security';
select set_config('request.jwt.claims', '{{"sub":"f5000000-0000-0000-0000-000000000001","role":"authenticated","aal":"aal1"}}', false);
select throws_ok($$ select public.set_require_admin_mfa(true) $$, 'WMS60', null, 'it cannot be switched on from a session that has not passed the second factor');

-- the matrix
create function pg_temp.masked(act text, exp text) returns text language sql immutable as $m$
  select string_agg(case when substr(exp, g, 1) = '?' then '?' else substr(act, g, 1) end, '' order by g) from generate_series(1, 5) g $m$;
create temp table actual as select tbl, op, string_agg(res, '' order by role) res from probe group by tbl, op;
select is(pg_temp.masked((select res from actual a where a.tbl = e.tbl and a.op = 'R'), e.r), e.r, e.tbl || ': who can read (A C M S X)') from expected e order by e.tbl;
select is(pg_temp.masked((select res from actual a where a.tbl = e.tbl and a.op = 'I'), e.i), e.i, e.tbl || ': who can insert (A C M S X)') from expected e order by e.tbl;
select is(pg_temp.masked((select res from actual a where a.tbl = e.tbl and a.op = 'U'), e.u), e.u, e.tbl || ': who can update (A C M S X)') from expected e order by e.tbl;
select is(pg_temp.masked((select res from actual a where a.tbl = e.tbl and a.op = 'D'), e.d), e.d, e.tbl || ': who can delete (A C M S X)') from expected e order by e.tbl;

select * from finish();
rollback;
"""
(root / 'supabase/tests/database/rls_matrix.test.sql').write_text(out)
print('written', n_tables, 'tables')
